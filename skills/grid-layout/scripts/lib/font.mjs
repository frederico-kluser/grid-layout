const GLYPH_W = 5;
const GLYPH_H = 7;
const SPACING = 1; // em unidades de escala

// Caixa vazia (tofu) para caracteres sem glifo.
const TOFU = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'];

export function glyph(ch) {
  const up = ch.toUpperCase();
  return G[up] || G[ch] || TOFU;
}

export function textSize(text, scale = 1) {
  const chars = [...String(text).toUpperCase()];
  const w = chars.length === 0 ? 0 : (chars.length * (GLYPH_W + SPACING) - SPACING) * scale;
  return { w, h: GLYPH_H * scale };
}

// Desenha texto em `img` ({width,height,data RGBA}). Cores [r,g,b,a] 0..255.
export function drawText(img, x, y, text, { scale = 1, color = [255, 255, 255, 255], bg = null, pad = 0 } = {}) {
  const s = Math.max(1, Math.round(scale));
  const chars = [...String(text).toUpperCase()];
  const { w, h } = textSize(text, s);
  if (bg) {
    fillRectRaw(img, x - pad, y - pad, w + pad * 2, h + pad * 2, bg);
  }
  let cx = x;
  for (const ch of chars) {
    const g = glyph(ch);
    for (let gy = 0; gy < GLYPH_H; gy++) {
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (g[gy][gx] !== '#') continue;
        fillRectRaw(img, cx + gx * s, y + gy * s, s, s, color);
      }
    }
    cx += (GLYPH_W + SPACING) * s;
  }
  return { w, h };
}

// Preenchimento com mistura alfa (não exportado: fonte é consumidora interna).
function fillRectRaw(img, x, y, w, h, [r, g, b, a = 255]) {
  const x0 = Math.max(0, Math.round(x));
  const y0 = Math.max(0, Math.round(y));
  const x1 = Math.min(img.width, Math.round(x) + Math.round(w));
  const y1 = Math.min(img.height, Math.round(y) + Math.round(h));
  const data = img.data;
  for (let yy = y0; yy < y1; yy++) {
    for (let xx = x0; xx < x1; xx++) {
      const i = (yy * img.width + xx) << 2;
      if (a >= 255) {
        data[i] = r; data[i + 1] = g; data[i + 2] = b; data[i + 3] = 255;
      } else {
        const t = a / 255;
        data[i] = Math.round(data[i] * (1 - t) + r * t);
        data[i + 1] = Math.round(data[i + 1] * (1 - t) + g * t);
        data[i + 2] = Math.round(data[i + 2] * (1 - t) + b * t);
        data[i + 3] = 255;
      }
    }
  }
}
